export interface SurfacingSpec extends CutCommon {
  x0: number;
  y0: number;
  x1: number;
  y1: number;
  /** % of the tool diameter between passes */
  stepoverPct: number;
  depthPerPass: number;
  totalDepth: number;
  /** Passes run along X (stepping in Y) or along Y */
  direction: 'x' | 'y';
}

/** Zig-zag facing: the tool centre covers the rectangle, so the tool reaches r beyond it. */
export function surfacing(s: SurfacingSpec): GeneratedJob {
  const errors: string[] = [];
  validateCommon(s, errors);
  if (!(s.x1 > s.x0) || !(s.y1 > s.y0)) errors.push('The area needs a positive width and depth.');
  if (!(s.stepoverPct > 0 && s.stepoverPct <= 95)) errors.push('Stepover must be between 1 and 95 % of the tool.');
  if (!(s.depthPerPass > 0) || !(s.totalDepth > 0)) errors.push('Depths must be above zero.');
  const name = 'surfacing.nc';
  if (errors.length) return { name, text: '', errors };
  const step = (s.toolDiameter * s.stepoverPct) / 100;
  const [a0, a1, b0, b1] = s.direction === 'x' ? [s.x0, s.x1, s.y0, s.y1] : [s.y0, s.y1, s.x0, s.x1];
  const rows: number[] = [];
  for (let b = b0; b < b1 - 1e-9; b += step) rows.push(b);
  rows.push(b1);
  const xy = (a: number, b: number) => (s.direction === 'x' ? `X${f(a)} Y${f(b)}` : `X${f(b)} Y${f(a)}`);
  const out = header('Surfacing', s, [`area X${f(s.x0)}..${f(s.x1)} Y${f(s.y0)}..${f(s.y1)}, ${f(s.totalDepth)} mm deep in passes of ${f(s.depthPerPass)} mm`], );
  for (const d of depthLevels(s.totalDepth, s.depthPerPass)) {
    out.push(`G0 ${xy(a0, rows[0]!)}`);
    out.push(`G1 Z${f(-d)} F${f(s.plungeFeed)}`);
    rows.forEach((b, i) => {
      if (i > 0) out.push(`G1 ${xy(i % 2 === 1 ? a1 : a0, b)}`);
      out.push(`G1 ${xy(i % 2 === 0 ? a1 : a0, b)}${i === 0 ? ` F${f(s.feed)}` : ''}`);
    });
    out.push(`G0 Z${f(s.clearance)}`);
  }
  return { name, text: [...out, ...footer(s)].join('\n'), errors };
}

