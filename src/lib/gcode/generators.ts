/**
 * Trace the rectangle around a job at a safe height with the spindle off, to
 * check it fits on the stock and clears the clamps. Starts and ends at the
 * front-left corner.
 */
export function outlineTrace(b: { min: ArrayLike<number>; max: ArrayLike<number> }, height: number, feed: number, name = 'job'): GeneratedJob {
  const errors: string[] = [];
  if (!(b.max[0]! >= b.min[0]!) || !(b.max[1]! >= b.min[1]!)) errors.push('The job has no extent in X/Y.');
  if (!(feed > 0)) errors.push('Feed must be above zero.');
  if (errors.length) return { name: `${name}-outline.nc`, text: '', errors };
  const [x0, y0, x1, y1] = [b.min[0]!, b.min[1]!, b.max[0]!, b.max[1]!];
  const text = [
    `(Outline of ${name}: spindle off, at Z${f(height)} — generated by CNC Sender)`,
    'G21 G90 G17 G94',
    'M5',
    `G0 Z${f(height)}`,
    `G0 X${f(x0)} Y${f(y0)}`,
    `G1 X${f(x1)} Y${f(y0)} F${f(feed)}`,
    `G1 X${f(x1)} Y${f(y1)}`,
    `G1 X${f(x0)} Y${f(y1)}`,
    `G1 X${f(x0)} Y${f(y0)}`,
    'M30',
  ].join('\n');
  return { name: `${name}-outline.nc`, text, errors };
}
