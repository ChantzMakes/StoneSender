export interface PocketSpec extends CutCommon {
  shape: 'rect' | 'circle';
  cx: number;
  cy: number;
  /** rect */
  width: number;
  height: number;
  /** circle */
  diameter: number;
  depth: number;
  stepdown: number;
  stepoverPct: number;
}

/** Pocket cleared from the centre outwards, one depth level at a time (plunges in the middle). */
export function pocket(p: PocketSpec): GeneratedJob {
  const errors: string[] = [];
  validateCommon(p, errors);
  const r = p.toolDiameter / 2;
  if (p.shape === 'rect' && !(p.width > p.toolDiameter && p.height > p.toolDiameter)) errors.push('The pocket must be wider and longer than the tool.');
  if (p.shape === 'circle' && !(p.diameter > p.toolDiameter)) errors.push('The pocket must be wider than the tool.');
  if (!(p.depth > 0) || !(p.stepdown > 0)) errors.push('Depths must be above zero.');
  if (!(p.stepoverPct > 0 && p.stepoverPct <= 95)) errors.push('Stepover must be between 1 and 95 % of the tool.');
  const name = p.shape === 'rect' ? 'pocket-rect.nc' : 'pocket-circle.nc';
  if (errors.length) return { name, text: '', errors };
  const step = (p.toolDiameter * p.stepoverPct) / 100;
  const desc = p.shape === 'rect' ? `${f(p.width)} × ${f(p.height)} mm` : `Ø${f(p.diameter)} mm`;
  const out = header('Pocket', p, [`${desc} centred on X${f(p.cx)} Y${f(p.cy)}, ${f(p.depth)} mm deep`]);
  for (const d of depthLevels(p.depth, p.stepdown)) {
    out.push(`G0 X${f(p.cx)} Y${f(p.cy)}`);
    out.push(`G1 Z${f(-d)} F${f(p.plungeFeed)}`);
    if (p.shape === 'rect') {
      const hx = p.width / 2 - r;
      const hy = p.height / 2 - r;
      // insets from the outermost contour inwards, cut innermost first
      const loops: [number, number][] = [];
      for (let k = 0; ; k++) {
        const ix = hx - k * step;
        const iy = hy - k * step;
        if (ix <= 1e-9 || iy <= 1e-9) {
          // centre line for the remaining strip
          const sx = Math.max(ix, 0);
          const sy = Math.max(iy, 0);
          if (sx > 1e-9 || sy > 1e-9) loops.push([sx, sy]);
          break;
        }
        loops.push([ix, iy]);
      }
      loops.reverse();
      let first = true;
      for (const [ix, iy] of loops) {
        const c = [
          [p.cx - ix, p.cy - iy],
          [p.cx + ix, p.cy - iy],
          [p.cx + ix, p.cy + iy],
          [p.cx - ix, p.cy + iy],
          [p.cx - ix, p.cy - iy],
        ];
        out.push(`G1 X${f(c[0]![0]!)} Y${f(c[0]![1]!)}${first ? ` F${f(p.feed)}` : ''}`);
        first = false;
        for (const [x, y] of c.slice(1)) out.push(`G1 X${f(x!)} Y${f(y!)}`);
      }
    } else {
      const R = p.diameter / 2 - r;
      const radii: number[] = [];
      for (let rr = R; rr > 1e-9; rr -= step) radii.push(rr);
      radii.reverse();
      let first = true;
      for (const rr of radii) {
        // step out along +X, then a full circle (climb in G3 is conventional for CCW inside)
        out.push(`G1 X${f(p.cx + rr)} Y${f(p.cy)}${first ? ` F${f(p.feed)}` : ''}`);
        first = false;
        out.push(`G3 X${f(p.cx + rr)} Y${f(p.cy)} I${f(-rr)} J0`);
      }
    }
    out.push(`G0 Z${f(p.clearance)}`);
  }
  return { name, text: [...out, ...footer(p)].join('\n'), errors };
}

