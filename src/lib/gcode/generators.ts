export interface DrillSpec extends Omit<CutCommon, 'feed'> {
  pattern: 'grid' | 'circle';
  /** grid */
  x0: number;
  y0: number;
  nx: number;
  ny: number;
  dx: number;
  dy: number;
  /** circle */
  cx: number;
  cy: number;
  radius: number;
  count: number;
  startAngle: number;
  depth: number;
  /** 0 = drill in one go */
  peck: number;
}

export function drillPoints(d: DrillSpec): [number, number][] {
  const pts: [number, number][] = [];
  if (d.pattern === 'grid') {
    for (let j = 0; j < d.ny; j++) {
      for (let k = 0; k < d.nx; k++) {
        const i = j % 2 === 0 ? k : d.nx - 1 - k; // serpentine
        pts.push([d.x0 + i * d.dx, d.y0 + j * d.dy]);
      }
    }
  } else {
    for (let i = 0; i < d.count; i++) {
      const a = ((d.startAngle + (360 * i) / d.count) * Math.PI) / 180;
      pts.push([d.cx + d.radius * Math.cos(a), d.cy + d.radius * Math.sin(a)]);
    }
  }
  return pts;
}

/** Drilling with optional pecking (full retract to 1 mm above the surface between pecks). */
export function drilling(d: DrillSpec): GeneratedJob {
  const errors: string[] = [];
  validateCommon({ ...d, feed: d.plungeFeed }, errors);
  if (!(d.depth > 0)) errors.push('Depth must be above zero.');
  if (d.peck < 0) errors.push('Peck depth must not be negative.');
  if (d.pattern === 'grid' && !(d.nx >= 1 && d.ny >= 1 && d.nx * d.ny <= 10000)) errors.push('Grid needs 1–10000 holes.');
  if (d.pattern === 'circle' && !(d.count >= 1 && d.count <= 1000 && d.radius > 0)) errors.push('Circle needs 1–1000 holes and a radius.');
  const name = 'drilling.nc';
  if (errors.length) return { name, text: '', errors };
  const pts = drillPoints(d);
  const out = header('Drilling', { ...d, feed: d.plungeFeed }, [`${pts.length} holes, ${f(d.depth)} mm deep${d.peck > 0 ? `, pecks of ${f(d.peck)} mm` : ''}`]);
  const levels = d.peck > 0 ? depthLevels(d.depth, d.peck) : [d.depth];
  for (const [x, y] of pts) {
    out.push(`G0 X${f(x)} Y${f(y)}`);
    out.push('G0 Z1');
    let prev = 0;
    for (const lvl of levels) {
      if (prev > 0) out.push(`G0 Z${f(-prev + 0.3)}`);
      out.push(`G1 Z${f(-lvl)} F${f(d.plungeFeed)}`);
      out.push('G0 Z1');
      prev = lvl;
    }
    out.push(`G0 Z${f(d.clearance)}`);
  }
  return { name, text: [...out, ...footer({ ...d, feed: d.plungeFeed })].join('\n'), errors };
}

