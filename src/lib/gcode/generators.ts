/**
 * Built-in generators (spec §5): surfacing, simple pockets, drilling patterns
 * and an outline trace of a job's boundary. They produce plain GRBL G-code in
 * mm, absolute, work coordinates, which is then loaded as a normal job (so it
 * gets the analysis, 3D preview and pre-flight like any file).
 *
 * Common shape: header comments, G21 G90 G17 G94, spindle on + spin-up dwell,
 * all travel at the clearance height, retract and M5 / M30 at the end.
 */

export interface CutCommon {
  toolDiameter: number;
  /** mm/min */
  feed: number;
  plungeFeed: number;
  rpm: number;
  /** Work Z for travel moves */
  clearance: number;
  /** Seconds to wait after M3 */
  spinUp: number;
}

export interface GeneratedJob {
  name: string;
  text: string;
  errors: string[];
}

const f = (v: number) => String(Number(v.toFixed(4)));

function validateCommon(c: CutCommon, errors: string[]) {
  if (!(c.toolDiameter > 0)) errors.push('Tool diameter must be above zero.');
  if (!(c.feed > 0) || !(c.plungeFeed > 0)) errors.push('Feeds must be above zero.');
  if (!(c.rpm >= 0)) errors.push('Spindle speed must not be negative.');
  if (!(c.clearance > 0)) errors.push('Clearance height must be above Z0.');
}

function header(title: string, c: CutCommon, lines: string[]): string[] {
  return [
    `(${title} — generated by CNC Sender)`,
    `(tool Ø${f(c.toolDiameter)} mm, feed ${f(c.feed)} mm/min, plunge ${f(c.plungeFeed)} mm/min)`,
    ...lines.map((l) => `(${l})`),
    'G21 G90 G17 G94',
    `G0 Z${f(c.clearance)}`,
    ...(c.rpm > 0 ? [`M3 S${f(c.rpm)}`, ...(c.spinUp > 0 ? [`G4 P${f(c.spinUp)}`] : [])] : []),
  ];
}

function footer(c: CutCommon): string[] {
  return [`G0 Z${f(c.clearance)}`, 'M5', 'M30'];
}

/** Depth levels from the first step down to the full depth (last one exact). */
export function depthLevels(total: number, step: number): number[] {
  const out: number[] = [];
  if (!(total > 0) || !(step > 0)) return out;
  for (let d = step; d < total - 1e-9; d += step) out.push(d);
  out.push(total);
  return out;
}

